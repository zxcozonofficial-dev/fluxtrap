def speaker_bar(name, role, mins):
    t = Table([[Paragraph(f"{name} &nbsp;&nbsp;—&nbsp;&nbsp; {role}", S["speaker"]),
                Paragraph(f'<font color="#FFFFFF">~{mins}</font>', S["cell"])]],
              colWidths=[133*mm, 27*mm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (-1,-1), NAVY),
        ("LEFTPADDING", (0,0), (-1,-1), 8), ("RIGHTPADDING", (0,0), (-1,-1), 8),
        ("TOPPADDING", (0,0), (-1,-1), 5), ("BOTTOMPADDING", (0,0), (-1,-1), 5),
        ("ALIGN", (1,0), (1,0), "RIGHT"), ("VALIGN", (0,0), (-1,-1), "MIDDLE"),
    ]))
    return t

def box(rows, widths, header=True):
    data = []
    for i, r in enumerate(rows):
        style = "cellb" if (header and i == 0) else "cell"
        data.append([Paragraph(c, S[style]) for c in r])
    t = Table(data, colWidths=widths, repeatRows=1 if header else 0)
    cmds = [
        ("GRID", (0,0), (-1,-1), 0.5, colors.HexColor("#C3CEDA")),
        ("VALIGN", (0,0), (-1,-1), "TOP"),
        ("LEFTPADDING", (0,0), (-1,-1), 7), ("RIGHTPADDING", (0,0), (-1,-1), 7),
        ("TOPPADDING", (0,0), (-1,-1), 5), ("BOTTOMPADDING", (0,0), (-1,-1), 5),
    ]
    if header:
        cmds += [("BACKGROUND", (0,0), (-1,0), NAVY),
                 ("ROWBACKGROUNDS", (0,1), (-1,-1), [colors.white, LIGHT])]
    else:
        cmds += [("BACKGROUND", (0,0), (-1,-1), LIGHT)]
    t.setStyle(TableStyle(cmds))
    return t

def callout(title, body):
    inner = [Paragraph(f'<font color="#1B3A5C"><b>{title}</b></font>', S["cell"]),
             Spacer(1, 3), Paragraph(body, S["cell"])]
    t = Table([[inner]], colWidths=[160*mm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (-1,-1), LIGHT),
        ("LINEBEFORE", (0,0), (0,-1), 3, GOLD),
        ("LEFTPADDING", (0,0), (-1,-1), 10), ("RIGHTPADDING", (0,0), (-1,-1), 10),
        ("TOPPADDING", (0,0), (-1,-1), 8), ("BOTTOMPADDING", (0,0), (-1,-1), 8),
    ]))
    return t

